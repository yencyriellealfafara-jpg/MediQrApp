/*
  What: Example modal screen used by the app's router.
  Which: Renders a simple message and a link back to home.
  Why: Demonstrates a modal route and how to dismiss it using expo-router's Link component.
  How: Uses themed components (ThemedView/ThemedText) for consistent styling and Link with dismissTo to close the modal and return to '/'.
*/
import { Link } from 'expo-router';
import { StyleSheet } from 'react-native';

import { ThemedText } from '@/components/themed-text';
import { ThemedView } from '@/components/themed-view';

export default function ModalScreen() {
  return (
    <ThemedView style={styles.container}>
      <ThemedText type="title">This is a modal</ThemedText>
      <Link href="/" dismissTo style={styles.link}>
        <ThemedText type="link">Go to home screen</ThemedText>
      </Link>
    </ThemedView>
  );
}

const styles = StyleSheet.create({
  container: {
    flex: 1,
    alignItems: 'center',
    justifyContent: 'center',
    padding: 20,
  },
  link: {
    marginTop: 15,
    paddingVertical: 15,
  },
});
